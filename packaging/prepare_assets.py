"""Regenerate packaging/THIRD_PARTY_NOTICES.txt and packaging/version_info.txt before a build.

Run with the build environment's Python (packaging\\build.ps1 does), so it sees the packages that
get bundled. Stdlib only. Adapted from the BIOMIS team's Timelapse Video Processing (MIT).

THIRD_PARTY_NOTICES.txt: the licence and licence files of every installed package, plus the parts
that are not Python packages: Qt/PySide6 (LGPL-3.0, text included), the Python runtime, the
Bio-Formats origin of the cellSens tag names and the GUI pieces taken from Timelapse Video
Processing.
"""
from __future__ import annotations

import importlib.metadata as metadata
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGING_DIR = ROOT / "packaging"
OUTPUT = PACKAGING_DIR / "THIRD_PARTY_NOTICES.txt"
VERSION_INFO = PACKAGING_DIR / "version_info.txt"

#: packages that are build or test tools only, never bundled into the app
NOT_BUNDLED = {"pip", "pyinstaller", "pyinstaller-hooks-contrib", "pytest", "pluggy", "iniconfig", "pygments",
               "altgraph", "pefile", "pywin32-ctypes", "colorama", "setuptools"}
MAX_FILE_BYTES = 1_000_000
LICENSE_KEYWORDS = ("license", "licence", "copying", "notice", "authors")

LGPL3_URL = "https://www.gnu.org/licenses/lgpl-3.0.txt"


def _is_license_like(filename: str) -> bool:
    lower = filename.lower()
    return any(keyword in lower for keyword in LICENSE_KEYWORDS)


def _read_capped(path: Path) -> str | None:
    try:
        size = path.stat().st_size
    except OSError:
        return None
    if size > MAX_FILE_BYTES:
        return f"[skipped: {size:,} bytes, over the {MAX_FILE_BYTES:,} byte cap]"
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None


def _distribution_section(dist: metadata.Distribution, seen: set[str]) -> list[str]:
    if dist.metadata is None:
        return []
    name = dist.metadata.get("Name")
    if not name or name.lower() in NOT_BUNDLED:
        return []
    licence = dist.metadata.get("License-Expression") or dist.metadata.get("License") or "see the notices below"
    if len(licence) > 200:
        licence = licence.splitlines()[0][:200] + " (full text below)"
    lines = ["", "=" * 72, f"{name} {dist.version or ''}", f"License: {licence}"]
    home = dist.metadata.get("Home-page") or next(
        (u.split(",", 1)[1].strip() for u in (dist.metadata.get_all("Project-URL") or []) if "," in u), "")
    if home:
        lines.append(f"Source: {home}")
    for entry in dist.files or ():
        if not _is_license_like(entry.name):
            continue
        candidate = Path(dist.locate_file(entry))
        key = str(candidate)
        if key in seen or not candidate.exists():
            continue
        seen.add(key)
        text = _read_capped(candidate)
        if text:
            lines += ["", f"--- {entry} ---", text]
    return lines


def _lgpl3_text() -> str:
    """LGPL-3.0 text as a bundled package ships it, else a pointer to it."""
    for dist in metadata.distributions():
        for entry in dist.files or ():
            if "lgpl" in entry.name.lower() or entry.name.lower() in ("copying.lesser",):
                p = Path(dist.locate_file(entry))
                text = _read_capped(p) or ""
                if "GNU LESSER GENERAL PUBLIC LICENSE" in text and "Version 3" in text:
                    return text
    return f"The full text of the GNU Lesser General Public License version 3 is at {LGPL3_URL}"



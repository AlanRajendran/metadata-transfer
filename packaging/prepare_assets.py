def write_version_info() -> str:
    init = (ROOT / "source" / "metadata_transfer" / "__init__.py").read_text(encoding="utf-8")
    version = re.search(r'__version__ = "([^"]+)"', init).group(1)
    parts = (tuple(int(p) for p in version.split(".")) + (0, 0, 0, 0))[:4]
    affiliation = re.search(r'AFFILIATION = "([^"]+)"', init).group(1)
    text = f"""# UTF-8 -- generated by packaging/prepare_assets.py, do not edit
VSVersionInfo(
  ffi=FixedFileInfo(filevers={parts}, prodvers={parts}, mask=0x3F, flags=0x0, OS=0x40004, fileType=0x1,
                    subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable(u"040904B0", [
      StringStruct(u"CompanyName", u"{affiliation}"),
      StringStruct(u"FileDescription", u"Metadata Transfer"),
      StringStruct(u"FileVersion", u"{version}"),
      StringStruct(u"InternalName", u"Metadata Transfer"),
      StringStruct(u"LegalCopyright", u"Copyright (c) 2026 the Metadata Transfer contributors, GPL-3.0-or-later"),
      StringStruct(u"OriginalFilename", u"Metadata Transfer.exe"),
      StringStruct(u"ProductName", u"Metadata Transfer"),
      StringStruct(u"ProductVersion", u"{version}"),
    ])]),
    VarFileInfo([VarStruct(u"Translation", [1033, 1200])]),
  ],
)
"""
    VERSION_INFO.write_text(text, encoding="utf-8")
    return version


def main() -> int:
    PACKAGING_DIR.mkdir(exist_ok=True)
    OUTPUT.write_text("\n".join(collect_notices()), encoding="utf-8")
    version = write_version_info()
    print(f"Wrote {OUTPUT} ({OUTPUT.stat().st_size:,} bytes) and {VERSION_INFO.name} ({version})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
